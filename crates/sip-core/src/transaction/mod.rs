//! Transaction layer (docs/design/sip-core.md section 4): the four RFC 3261 state machines
//! with the RFC 6026 Accepted state, transaction matching (17.1.3 / 17.2.3) and automatic
//! CANCEL handling.
//!
//! The state machines ([`ServerInvite`], [`ServerNonInvite`], [`ClientInvite`],
//! [`ClientNonInvite`]) are pure: feed them messages and timer expiries, observe the returned
//! [`Action`]s. [`TransactionLayer`] runs them in tokio tasks on top of the transport channels.

