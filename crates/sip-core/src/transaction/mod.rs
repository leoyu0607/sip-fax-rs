/// The RFC 3261 magic cookie that starts every branch generated by a compliant UA.
pub const MAGIC_COOKIE: &str = "z9hG4bK";

/// Server transaction identity (RFC 3261 17.2.3): branch + sent-by of the topmost Via + method
/// (ACK is matched against INVITE).
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct ServerKey {
    /// Via branch parameter.
    pub branch: String,
    /// Via sent-by host, lower-cased.
    pub host: String,
    /// Via sent-by port (5060 when absent).
    pub port: u16,
    /// Request method; ACK is mapped to INVITE.
    pub method: Method,
}

impl ServerKey {
    /// Key of a received request. `None` when the topmost Via is unusable or its branch lacks
    /// the magic cookie (RFC 2543 style matching is not supported).
    pub fn from_request(req: &Request) -> Option<ServerKey> {
        let via = req.headers.top_via().ok()?;
        let branch = via.branch()?;
        if !branch.starts_with(MAGIC_COOKIE) {
            return None;
        }
        let method = match &req.method {
            Method::Ack => Method::Invite,
            m => m.clone(),
        };
        Some(ServerKey {
            branch: branch.to_string(),
            host: via.host.to_ascii_lowercase(),
            port: via.port.unwrap_or(DEFAULT_PORT),
            method,
        })
    }
}

/// Client transaction identity (RFC 3261 17.1.3): branch of the topmost Via + CSeq method.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct ClientKey {
    /// Via branch parameter.
    pub branch: String,
    /// Method (request line for requests, CSeq method for responses).
    pub method: Method,
}

impl ClientKey {
    /// Key of an outgoing request.
    pub fn from_request(req: &Request) -> Option<ClientKey> {
        let branch = req.headers.top_via().ok()?.branch()?.to_string();
        Some(ClientKey {
            branch,
            method: req.method.clone(),
        })
    }

    /// Key a received response belongs to.
    pub fn from_response(resp: &Response) -> Option<ClientKey> {
        let branch = resp.headers.top_via().ok()?.branch()?.to_string();
        Some(ClientKey {
            branch,
            method: resp.headers.cseq().ok()?.method,
        })
    }
}

/// Transaction-layer errors.
#[derive(Debug, thiserror::Error)]
pub enum TransactionError {
    /// ACK is not a transaction; send it through the transport directly.
    #[error("ACK has no client transaction")]
    AckHasNoTransaction,
    /// A client transaction with the same branch and method is already running.
    #[error("duplicate client transaction")]
    Duplicate,
    /// The request has no usable Via header.
    #[error("request has no usable Via")]
    NoVia,
    /// The transaction has already ended or the layer is shut down.
    #[error("transaction closed")]
    Closed,
}

/// TU-side handle of a server transaction.
#[derive(Clone)]
pub struct ServerTx {
    cmd: mpsc::Sender<Cmd>,
}

impl ServerTx {
    /// Passes a response to the transaction (it sends and retransmits as the RFC requires).
    pub async fn respond(&self, resp: Response) -> Result<(), TransactionError> {
        self.cmd
            .send(Cmd::Respond(resp))
            .await
            .map_err(|_| TransactionError::Closed)
    }
}

/// A new request delivered to the TU together with its server transaction.
pub struct IncomingRequest {
    /// The request; its topmost Via carries `received` / `rport`.
    pub request: Request,
    /// Remote address.
    pub source: SocketAddr,
    /// Transport it arrived on.
    pub transport: TransportKind,
    /// Local address it arrived on.
    pub local: SocketAddr,
    /// Handle to answer with.
    pub tx: ServerTx,
    /// Transaction events (ACK in Accepted state, CANCEL, Timer H, transport error). The
    /// channel closes when the transaction terminates.
    pub events: mpsc::UnboundedReceiver<TuEvent>,
}

/// Everything the layer hands to the TU.
pub enum TuInput {
    /// A new request with its server transaction.
    Request(IncomingRequest),
    /// An ACK that matched no INVITE server transaction (the normal case for the ACK of a
    /// 2xx, RFC 3261 13.2.2.4).
    Ack(Incoming),
    /// A response that matched no client transaction (e.g. a retransmitted 2xx after the
    /// INVITE transaction ended, or a forked 2xx).
    StrayResponse(Incoming),
    /// A request whose branch lacks the RFC 3261 magic cookie: RFC 2543 transaction matching
    /// is not supported, so no transaction is created and the TU must cope statelessly.
    Stateless(Incoming),
}

/// TU-side handle of a client transaction.
pub struct ClientTx {
    /// The request as sent (Via stamped, branch filled in).
    pub request: Request,
    /// Responses, timeout and transport errors; closes when the transaction terminates.
    pub events: mpsc::UnboundedReceiver<TuEvent>,
}

struct Inner {
    transport: TransportHandle,
    cfg: TimerConfig,
    tu: mpsc::UnboundedSender<TuInput>,
    servers: Mutex<HashMap<ServerKey, mpsc::Sender<Cmd>>>,
    clients: Mutex<HashMap<ClientKey, mpsc::Sender<Cmd>>>,
    shutdown: watch::Receiver<bool>,
    tasks: Tasks,
}

fn lock<T>(m: &Mutex<T>) -> std::sync::MutexGuard<'_, T> {
    m.lock().unwrap_or_else(|e| e.into_inner())
}

/// Generates a fresh RFC 3261 branch value.
pub fn new_branch() -> String {
    format!("{MAGIC_COOKIE}{:016x}", rand::random::<u64>())
}

/// The transaction layer: matches messages to transactions, runs them, and talks to the TU.
#[derive(Clone)]
pub struct TransactionLayer {
    inner: Arc<Inner>,
    stop: Arc<watch::Sender<bool>>,
}

impl TransactionLayer {
    /// Starts the layer on top of a transport. Returns the layer and the stream of inputs for
    /// the TU.
    pub fn new(
        transport: TransportHandle,
        incoming: mpsc::Receiver<Incoming>,
        cfg: TimerConfig,
    ) -> (TransactionLayer, mpsc::UnboundedReceiver<TuInput>) {
        let (tu, tu_rx) = mpsc::unbounded_channel();
        let (stop, stop_rx) = watch::channel(false);
        let inner = Arc::new(Inner {
            transport,
            cfg,
            tu,
            servers: Mutex::new(HashMap::new()),
            clients: Mutex::new(HashMap::new()),
            shutdown: stop_rx.clone(),
            tasks: Tasks::default(),
        });
        let dispatcher = inner.clone();
        inner
            .tasks
            .spawn(dispatcher.run_dispatcher(incoming, stop_rx));
        (
            TransactionLayer {
                inner,
                stop: Arc::new(stop),
            },
            tu_rx,
        )
    }

    /// The transport handle (for sending ACKs of 2xx and other stateless messages).
    pub fn transport(&self) -> &TransportHandle {
        &self.inner.transport
    }

    /// The timer configuration in use.
    pub fn timer_config(&self) -> TimerConfig {
        self.inner.cfg
    }

    /// Number of running (server, client) transactions.
    pub fn transaction_counts(&self) -> (usize, usize) {
        (
            lock(&self.inner.servers).len(),
            lock(&self.inner.clients).len(),
        )
    }

    /// Starts a client transaction for `req` towards `dest`. The topmost Via is stamped with
    /// the advertised sent-by; a missing Via or branch is generated.
    pub fn send_request(
        &self,
        mut req: Request,
        dest: SocketAddr,
        kind: TransportKind,
    ) -> Result<ClientTx, TransactionError> {
        if req.method == Method::Ack {
            return Err(TransactionError::AckHasNoTransaction);
        }
        self.inner.transport.stamp_request(&mut req, kind, dest);
        let mut via = req.headers.top_via().map_err(|_| TransactionError::NoVia)?;
        if via.branch().is_none() {
            via.set_param("branch", Some(new_branch()));
            req.headers.set_first("Via", via.to_string());
        }
        let key = ClientKey::from_request(&req).ok_or(TransactionError::NoVia)?;
        let (cmd_tx, cmd_rx) = mpsc::channel(32);
        let (ev_tx, ev_rx) = mpsc::unbounded_channel();
        {
            let mut clients = lock(&self.inner.clients);
            if clients.contains_key(&key) {
                return Err(TransactionError::Duplicate);
            }
            clients.insert(key.clone(), cmd_tx);
        }
        let io = Io::Client { dest, kind };
        let inner = self.inner.clone();
        let cfg = inner.cfg;
        let reliable = kind.is_reliable();
        let sent = req.clone();
        let shutdown = inner.shutdown.clone();
        let transport = inner.transport.clone();
        let task = async move {
            if sent.method == Method::Invite {
                let (m, init) = ClientInvite::new(sent, reliable, cfg);
                drive(m, init, cmd_rx, transport, io, Some(ev_tx), shutdown).await;
            } else {
                let (m, init) = ClientNonInvite::new(sent, reliable, cfg);
                drive(m, init, cmd_rx, transport, io, Some(ev_tx), shutdown).await;
            }
            lock(&inner.clients).remove(&key);
        };
        self.inner.tasks.spawn(task);
        Ok(ClientTx {
            request: req,
            events: ev_rx,
        })
    }

    /// Stops the dispatcher and all transactions and waits for their tasks.
    pub async fn shutdown(&self) {
        let _ = self.stop.send(true);
        self.inner.tasks.join_all().await;
        lock(&self.inner.servers).clear();
        lock(&self.inner.clients).clear();
    }
}

impl Inner {
    async fn run_dispatcher(
        self: Arc<Self>,
        mut incoming: mpsc::Receiver<Incoming>,
        mut stop: watch::Receiver<bool>,
    ) {
        loop {
            let inc = tokio::select! {
                i = incoming.recv() => match i { Some(i) => i, None => return },
                () = crate::transport::wait_shutdown(&mut stop) => return,
            };
            self.dispatch(inc).await;
        }
    }

    async fn dispatch(self: &Arc<Self>, inc: Incoming) {
        match inc.msg.clone() {
            SipMessage::Response(resp) => {
                let tx = ClientKey::from_response(&resp)
                    .and_then(|k| lock(&self.clients).get(&k).cloned());
                match tx {
                    Some(tx) => {
                        let _ = tx.send(Cmd::Message(SipMessage::Response(resp))).await;
                    }
                    None => {
                        let _ = self.tu.send(TuInput::StrayResponse(inc));
                    }
                }
            }
            SipMessage::Request(req) => self.dispatch_request(req, inc).await,
        }
    }

    async fn dispatch_request(self: &Arc<Self>, req: Request, inc: Incoming) {
        let Some(key) = ServerKey::from_request(&req) else {
            tracing::warn!(source = %inc.source, method = %req.method,
                "request without RFC 3261 magic cookie: no transaction, passed to TU");
            let _ = self.tu.send(TuInput::Stateless(inc));
            return;
        };
        let existing = lock(&self.servers).get(&key).cloned();
        match req.method {
            Method::Ack => match existing {
                Some(tx) => {
                    let _ = tx.send(Cmd::Message(SipMessage::Request(req))).await;
                }
                None => {
                    let _ = self.tu.send(TuInput::Ack(inc));
                }
            },
            Method::Cancel => self.on_cancel(key, existing, req, inc).await,
            _ => match existing {
                Some(tx) => {
                    let _ = tx.send(Cmd::Message(SipMessage::Request(req))).await;
                }
                None => {
                    let (tx, events) = self.spawn_server(key, &req, &inc, true);
                    let events = events.unwrap_or_else(|| mpsc::unbounded_channel().1);
                    let _ = self.tu.send(TuInput::Request(IncomingRequest {
                        request: req,
                        source: inc.source,
                        transport: inc.transport,
                        local: inc.local,
                        tx: ServerTx { cmd: tx },
                        events,
                    }));
                }
            },
        }
    }

    /// RFC 3261 9.2: CANCEL is answered by the UAS transaction layer itself.
    async fn on_cancel(
        self: &Arc<Self>,
        cancel_key: ServerKey,
        existing: Option<mpsc::Sender<Cmd>>,
        req: Request,
        inc: Incoming,
    ) {
        if let Some(tx) = existing {
            // Retransmitted CANCEL: its own non-INVITE transaction resends the answer.
            let _ = tx.send(Cmd::Message(SipMessage::Request(req))).await;
            return;
        }
        let invite_key = ServerKey {
            method: Method::Invite,
            ..cancel_key.clone()
        };
        let invite_tx = lock(&self.servers).get(&invite_key).cloned();
        let (tx, _) = self.spawn_server(cancel_key, &req, &inc, false);
        let tag = format!("{:08x}", rand::random::<u32>());
        match invite_tx {
            Some(itx) => {
                let ok = Response::for_request(&req, StatusCode::OK, Some(&tag));
                let _ = tx.send(Cmd::Respond(ok)).await;
                let _ = itx.send(Cmd::Cancel).await;
            }
            None => {
                let no = Response::for_request(&req, StatusCode::CALL_DOES_NOT_EXIST, Some(&tag));
                let _ = tx.send(Cmd::Respond(no)).await;
            }
        }
    }

    /// Creates and starts a server transaction. With `tu_events` the TU gets an event channel.
    fn spawn_server(
        self: &Arc<Self>,
        key: ServerKey,
        req: &Request,
        inc: &Incoming,
        tu_events: bool,
    ) -> (mpsc::Sender<Cmd>, Option<mpsc::UnboundedReceiver<TuEvent>>) {
        let (cmd_tx, cmd_rx) = mpsc::channel(32);
        let (ev_tx, ev_rx) = if tu_events {
            let (a, b) = mpsc::unbounded_channel();
            (Some(a), Some(b))
        } else {
            (None, None)
        };
        lock(&self.servers).insert(key.clone(), cmd_tx.clone());
        let io = Io::Server {
            source: inc.source,
            kind: inc.transport,
        };
        let reliable = inc.transport.is_reliable();
        let cfg = self.cfg;
        let transport = self.transport.clone();
        let shutdown = self.shutdown.clone();
        let this = self.clone();
        let req = req.clone();
        self.tasks.spawn(async move {
            if req.method == Method::Invite {
                let (m, init) = ServerInvite::new(req, reliable, cfg);
                drive(m, init, cmd_rx, transport, io, ev_tx, shutdown).await;
            } else {
                let m = ServerNonInvite::new(req, reliable, cfg);
                drive(m, Vec::new(), cmd_rx, transport, io, ev_tx, shutdown).await;
            }
            lock(&this.servers).remove(&key);
        });
        (cmd_tx, ev_rx)
    }
}
